// Rasterises Natural Earth land (world-atlas land-110m.json, TopoJSON) into the
// dot-matrix grid used by the stats dashboard map.
//   npm pack world-atlas@2 && tar xzf world-atlas-*.tgz
//   node scripts/world-map.mjs package/land-110m.json > src/stats/worldMap.ts
import { readFileSync } from 'node:fs'

const STEP = 2 // degrees per dot
const LAT_TOP = 84
const LAT_BOTTOM = -58

const topo = JSON.parse(readFileSync(process.argv[2], 'utf8'))
const { scale, translate } = topo.transform

const arcs = topo.arcs.map((arc) => {
  let x = 0
  let y = 0
  return arc.map(([dx, dy]) => {
    x += dx
    y += dy
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]]
  })
})

function ring(indexes) {
  return indexes.flatMap((i, n) => {
    const points = i < 0 ? [...arcs[~i]].reverse() : arcs[i]
    return n === 0 ? points : points.slice(1)
  })
}

const rings = []
for (const geometry of topo.objects.land.geometries) {
  const polygons = geometry.type === 'Polygon' ? [geometry.arcs] : geometry.arcs
  for (const polygon of polygons) for (const r of polygon) rings.push(ring(r))
}

function inside(lon, lat) {
  let hit = false
  for (const points of rings) {
    for (let i = 0, j = points.length - 1; i < points.length; j = i++) {
      const [xi, yi] = points[i]
      const [xj, yj] = points[j]
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit
    }
  }
  return hit
}

const rows = []
for (let lat = LAT_TOP - STEP / 2; lat > LAT_BOTTOM; lat -= STEP) {
  let row = ''
  for (let lon = -180 + STEP / 2; lon < 180; lon += STEP) row += inside(lon, lat) ? '#' : '.'
  rows.push(row)
}

console.log(`// Generated by scripts/world-map.mjs from Natural Earth (world-atlas land-110m). Do not edit.
export const WORLD_MAP = {
  step: ${STEP},
  latTop: ${LAT_TOP},
  rows: [
${rows.map((r) => `    '${r}',`).join('\n')}
  ],
}`)
